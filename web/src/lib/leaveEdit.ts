// Уход из формы с несохранённым (M7.2, ревью задачи 10, круг 2; финальное ревью, I1; M7.3 §6.14
// п. 4): один вопрос для формы правки записи (`EntryEdit` — переход по адресу и действия журнала,
// которые закрыли бы форму), полей карточек на виду (шаг задачи) и форм карточек «Идей». Свой
// модуль: его импортирует основной чанк (`TasksView`, журналы), а `entryEdit.ts` — только ленивый
// чанк формы. С M7.3 проверка ставится в стек проверок ухода роутера (`pushGuard`, `guards.ts`):
// формы одной страницы больше не снимают проверки друг друга.
import { pushGuard } from './router';

/** Вопрос о несохранённом — общий у окна формы, панели журнала и перехода по адресу. */
export { LEAVE_EDIT } from './guards';

/**
 * Защита несохранённого на время жизни формы или журнала: переход по адресу (запись из Ctrl+K,
 * ссылка, пункт журнала, «назад») при `dirty()` сначала спрашивает `LEAVE_EDIT` — один вопрос на
 * весь стек проверок (текст верхней грязной); закрытие и перезагрузка вкладки — `beforeunload`
 * роутера. `dirty` — признак владельца формы (сравнение полей с записью), читается в момент
 * перехода: форма, которую журнал уже закрыл (или решил закрыть), отвечает `false`. `release` —
 * человек согласился уйти (вопрос задан один раз на весь стек): набранное отпускается. Возвращает
 * снятие защиты (для `onMount`).
 */
export function guardLeave(dirty: () => boolean, release?: () => void): () => void {
  return pushGuard({ dirty: () => dirty(), release });
}
