// Стек проверок ухода (M7.3, спецификация §6.14 п. 4; задача k:01M83ZDF5WED9AH9WVFF1S234C).
//
// До M7.3 у роутера была одна проверка ухода (`setGuard`): форма, поставившая её позже, снимала
// прежнюю, и формы статуса, новой задачи и шага на доске при уходе по адресу не спрашивали. Теперь
// каждая форма с набранным — открытое окно `FormDialog`, форма правки `EntryEdit`, редактор заметки,
// поле на виду (шаг задачи) — ставит свою проверку в общий стек:
// - переход по адресу при любой «грязной» проверке спрашивает **один раз** — текстом верхней
//   грязной (поставленной последней);
// - согласие вызывает `release()` у всех проверок стека (их формы закроются вместе с переходом и
//   больше не спрашивают), отказ оставляет всё как было;
// - `beforeunload` срабатывает, если грязная хоть одна (`anyDirty`).
// Цена (решение 82): при двух формах с набранным человек видит один вопрос — о верхней, а теряет
// набранное в обеих.
//
// Модуль без DOM и без runtime-импортов: проверяется `node --test` (`test/guards.test.ts`). Экземпляр
// с `window.confirm` — у роутера (`pushGuard`, `router.ts`).

/** Вопрос о несохранённом в форме — одинаковый у окна формы, панели журнала и перехода по адресу
 * (текст прежнего `leaveEdit.ts`). */
export const LEAVE_EDIT = 'В форме есть несохранённый текст. Закрыть её без сохранения?';

/**
 * Проверка ухода. `dirty(next)` — в форме есть несохранённое (читается в момент перехода; `next` —
 * адрес, куда уходят: редактор заметки свободен внутри своей заметки); `question` — свой текст
 * вопроса (по умолчанию `LEAVE_EDIT`); `release` — человек согласился уйти: набранное отпускается,
 * повторный переход форма не спрашивает.
 */
export type Guard<R = unknown> = {
  dirty: (next?: R) => boolean;
  question?: string;
  release?: () => void;
};

export interface Guards<R = unknown> {
  /** Поставить проверку на вершину стека; возвращает её снятие (снимает только свою запись). */
  push(g: Guard<R>): () => void;
  /** Можно ли уйти на `next`: нет грязных — да; иначе один вопрос `ask` текстом верхней грязной.
   * Согласие отпускает все проверки (`release`). */
  allow(next?: R): boolean;
  /** Грязная хоть одна (закрытие и перезагрузка вкладки — `beforeunload`). */
  anyDirty(): boolean;
}

/** Стек проверок ухода; `ask(question)` — синхронный вопрос (`true` — уйти). */
export function createGuards<R = unknown>(ask: (question: string) => boolean): Guards<R> {
  /** Записи стека: одна проверка может стоять дважды — снятие убирает свою запись. */
  const stack: { g: Guard<R> }[] = [];
  return {
    push(g) {
      const slot = { g };
      stack.push(slot);
      return () => {
        const i = stack.indexOf(slot);
        if (i >= 0) stack.splice(i, 1);
      };
    },
    allow(next) {
      let top: Guard<R> | null = null;
      for (let i = stack.length - 1; i >= 0 && !top; i--) if (stack[i].g.dirty(next)) top = stack[i].g;
      if (!top) return true;
      if (!ask(top.question ?? LEAVE_EDIT)) return false;
      // снимок: `release` формы может снять её проверку со стека
      for (const s of [...stack]) s.g.release?.();
      return true;
    },
    anyDirty() {
      return stack.some((s) => s.g.dirty());
    },
  };
}
