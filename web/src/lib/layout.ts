// Ширины адаптивной вёрстки WebUI (M7.2, спецификация §5.1) — один источник чисел.
//
// Классы ширины окна: телефон < 720 px (дерево и разделы — в выдвижной панели), планшет
// 720–1023 px (дерево — в панели, разделы — в шапке короткими подписями), настольный ≥ 1024 px
// (дерево постоянное: 260 px до 1279, 300 px с 1280). Раскладка журнала «список — карточка»
// (`JournalSplit.svelte`) и доска задач выбираются по ширине своей области, а не окна:
// `SPLIT_MIN`, `BOARD_MIN`.
//
// В CSS числа те же: переменные в `@media` и `@container` не работают, поэтому тест
// `web/test/layout.test.ts` пропускает в них только ширины этого файла (419/420, 719/720,
// 1023/1024, 1279/1280, 1439/1440 и 839/840). Модуль без runtime-импортов: его читает `node --test`.

/** Узкий телефон: ниже — без названия в шапке. */
export const BP_NARROW = 420;
/** Планшет: от этой ширины окна. */
export const BP_TABLET = 720;
/** Настольный: от этой ширины окна дерево постоянное. */
export const BP_DESKTOP = 1024;
/** Широкий настольный: дерево 300 px вместо 260. */
export const BP_WIDE = 1280;
/** Шапка: от этой ширины окна разделы — полными подписями, ниже — короткими (M7.3: в шапке ещё
 * «Проверка» и «Кандидаты N»). */
export const BP_FULL_LABELS = 1440;
/** Область журнала от этой ширины — список и карточка рядом (`JournalSplit`). */
export const SPLIT_MIN = 840;
/** Область доски задач от этой ширины — колонки статусов, ниже — вкладки (§5.2). */
export const BOARD_MIN = 840;

export type WidthClass = 'phone' | 'tablet' | 'desktop';

/** Класс ширины окна `w` (CSS px). */
export function widthClass(w: number): WidthClass {
  if (w < BP_TABLET) return 'phone';
  if (w < BP_DESKTOP) return 'tablet';
  return 'desktop';
}

/** Медиазапросы классов ширины и сенсорного ввода — для `matchMedia` (`viewport.svelte.ts`). */
export const MEDIA = {
  /** Телефон. */
  phone: `(max-width: ${BP_TABLET - 1}px)`,
  /** Дерево — выдвижная панель (телефон и планшет). */
  drawer: `(max-width: ${BP_DESKTOP - 1}px)`,
  /** Сенсорный ввод: цели касания 44 px, шрифт полей 16 px. */
  coarse: '(pointer: coarse)',
} as const;
