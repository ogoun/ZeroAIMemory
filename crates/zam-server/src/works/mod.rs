//! Внутренние работы памяти (M7.3 §6): работа памяти над собственными записями, где нужен текст
//! модели (пробы ночной проверки, кандидаты в Rules), — исполнитель «выкл / агент / подключённая
//! модель» и ночная часть сервера.
//!
//! - [`settings`] — настройки пользователя `works.*` и действующий режим вида;
//! - [`schedule`] — «пора ли» ночи на окне с часовым поясом;
//! - [`night`] — ночной исполнитель [`NightRunner`] и контекст ночи [`NightCtx`];
//! - [`queue`] — очередь работ (постановка ночи, снятие при смене режима, возврат при старте);
//! - [`egress`], [`model`], [`conn`], [`exec`], [`pause`] — клиент подключённой модели (задача 2):
//!   адреса и данные наружу, протокол, подключение и проверка, выполнение пакета, пауза и аудит.
//! - [`kinds`], [`package`] — виды работ (сборщик, инструкция, схема, проверка элемента) и
//!   построитель пакета с общей проверкой текста итога (задача 3).

pub mod conn;
pub mod egress;
pub mod exec;
pub mod kinds;
pub mod model;
pub mod night;
pub mod package;
pub mod pause;
pub mod queue;
