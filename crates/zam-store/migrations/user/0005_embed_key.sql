-- user DB, §6.3, §8.1 ТЗ (этап M2): ключ кэша эмбеддингов в чанках, владелец служебных
-- эмбеддингов (сборка мусора кэша).

-- Ключ кэша `embeddings` чанка: blake3 hex эмбеддируемой строки (контекстный префикс +
-- "\n" + текст, zam_store::embed_key_of). Пишется вместе с чанком и при пересчёте
-- префикса (перенос, переименование). Строки, созданные до v5, получают ключ при
-- открытии базы (`UserDbs::get`): формула ключа есть только в Rust.
-- Нужен воркеру (поиск в кэше), пересборке Qdrant из кэша без чтения текстов, выбору
-- лучшего листа в поиске и сборке мусора `embeddings`.
ALTER TABLE chunks ADD COLUMN embed_key TEXT;
CREATE INDEX chunks_embed_key ON chunks (embed_key);

-- Владелец эмбеддинга, которого нет среди чанков: id узла для предложений-кандидатов
-- автоматического L0 заметки и L0 папки; NULL — эмбеддинг чанка (живёт, пока на ключ
-- ссылается хотя бы один чанк). Служебная строка живёт, пока жив её узел и она входит
-- в текущий набор его ключей.
ALTER TABLE embeddings ADD COLUMN owner TEXT;
CREATE INDEX embeddings_owner ON embeddings (owner) WHERE owner IS NOT NULL;
